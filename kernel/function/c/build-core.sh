#!/usr/bin/env bash
# Builds the C SDK for the core's user target (item 5.2b, system design 5B), and the C functions
# that run on it as static native programs:
#
#   kernel/function/c/build-core.sh
#
# Into TARGET/core (TARGET being CARGO_TARGET_DIR or kernel/function/c/target):
#   lib/libmoruna_function.a  std, the SDK (moruna-function) and relibc on Moruna's platform:
#                             one crate graph, one runtime, std's _start (5B)
#   lib/libopenlibm.a         the C math library (kernel/vendor/relibc/openlibm)
#   include/                  relibc's headers (its own, and cbindgen's from its sources,
#                             committed in kernel/vendor/relibc/include-generated by its
#                             regen-headers.sh), openlibm's, and moruna_function.h
#   bin/double                examples/double.c
#   bin/sum                   the aggregate test (tests/c/scenarios.c, moruna_test_sum)
#   bin/runtime               tests/c/runtime.c: malloc, pthread_create, a thread_local, stderr
#   bin/params                tests/c/params.c: its params, moruna_params and getenv (item 5.5)
#   bin/threads               tests/threads.rs: std's thread-locals on the C library's threads
#                             and the C library's on std's
#   bin/libc-tests            relibc's own C tests that need only what Moruna has (step 5)
#   debug/NAME.debug         each program's debug info, which bin/NAME names (its
#                             .gnu_debuglink): the programs are stripped
#
# The archive is built as kernel/tools/build-std.sh builds a program with std (the kernel's
# nightly, std from kernel/vendor/rust-std/library, offline, its flags); the C is compiled to ELF
# by the host's clang (CC) for x86_64-unknown-none-elf, with __moruna__ defined, against those
# headers only; the programs are linked by rust-lld with kernel/targets/x86_64-moruna.ld, static.
# Nothing but the toolchain, clang and make is needed: no header is generated here.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
kernel="$(cd "$here/../.." && pwd)"
relibc="$kernel/vendor/relibc"
library="$kernel/vendor/rust-std/library"
target="$kernel/targets/x86_64-moruna.json"
script="$kernel/targets/x86_64-moruna.ld"
toolchain=nightly-2026-07-21
cargo_target="${CARGO_TARGET_DIR:-$here/target}"
out="$cargo_target/core"
cc="${CC:-cc}"

sysroot="$(rustup run "$toolchain" rustc --print sysroot)"
host="$(rustup run "$toolchain" rustc -vV | sed -n 's/^host: //p')"
tools="$sysroot/lib/rustlib/$host/bin"
ar="$tools/llvm-ar"
lld="$tools/rust-lld"
objcopy="$tools/llvm-objcopy"
resource="$("$cc" -print-resource-dir)/include"

# The C side of the user target: x86_64 ELF, SysV ABI, no red zone, static and not PIC, TLS by
# the local-exec model, as the Rust side is built (x86_64-moruna.json, build-std.sh's flags).
cflags=(--target=x86_64-unknown-none-elf -D__moruna__ -mno-red-zone -fno-stack-protector
  -fno-pic -fno-pie -ftls-model=local-exec -O2 -g)
# Against the C library's headers, then the compiler's own (float.h, stdarg.h and the like).
includes=(-nostdinc -isystem "$out/include" -isystem "$resource")

mkdir -p "$out/lib" "$out/include" "$out/bin" "$out/obj" "$out/debug"

# 1. The archive: std, the SDK and relibc, with std's _start; and tests/threads.rs, a Rust
# program on them. build-std.sh's flags exactly, its digest of std's sources included, so a
# target directory that is kept (a shared one, or build.sh's, where build-std.sh builds too)
# rebuilds std when they change, and only then.
flags="-C relocation-model=static -C relro-level=off -C force-unwind-tables=yes -C no-redzone=y"
flags="$flags -Zunstable-options -C link-arg=-T$script -C link-arg=-static"
flags="$flags --cfg getrandom_backend=\"custom\""
inputs="$(python3 - "$kernel/.." <<'PY'
import hashlib, os, sys
root = sys.argv[1]
digest = hashlib.sha256()
for top in ("kernel/vendor/rust-std/library", "kernel/sys", "kernel/abi", "crates/moruna-record", "kernel/targets"):
    for here, dirs, files in os.walk(os.path.join(root, top)):
        dirs[:] = sorted(d for d in dirs if d != "target")
        for name in sorted(files):
            path = os.path.join(here, name)
            digest.update(os.path.relpath(path, root).encode() + b"\0")
            with open(path, "rb") as f:
                digest.update(hashlib.sha256(f.read()).digest())
print(digest.hexdigest()[:16])
PY
)"
flags="$flags -C metadata=moruna-std-$inputs"
unset CARGO_ENCODED_RUSTFLAGS
# The SDK's crates are fetched first; the build then runs --offline, as build-std.sh's does.
rustup run "$toolchain" cargo fetch --locked --manifest-path "$here/Cargo.toml"
CC_x86_64_moruna="$cc" AR_x86_64_moruna="$ar" CFLAGS_x86_64_moruna="${cflags[*]}" \
__CARGO_TESTS_ONLY_SRC_ROOT="$library" RUSTFLAGS="$flags" \
  rustup run "$toolchain" cargo build --release --locked --offline \
  --manifest-path "$here/Cargo.toml" --lib --test threads \
  --target "$target" -Zunstable-options -Zjson-target-spec \
  -Zbuild-std=std,panic_abort -Zbuild-std-features=compiler-builtins-mem \
  --message-format=json-render-diagnostics >"$out/obj/cargo.json"
cp "$cargo_target/x86_64-moruna/release/libmoruna_function.a" "$out/lib/"
threads="$(python3 -c '
import json, sys
for line in open(sys.argv[1]):
    m = json.loads(line)
    if m.get("reason") == "compiler-artifact" and m["target"]["name"] == "threads" and m.get("executable"):
        print(m["executable"])
' "$out/obj/cargo.json")"

# 2. The headers: relibc's own, openlibm's, the ones cbindgen made from each of relibc's header
# modules (not its Rust math, which openlibm's replaces), committed, and the SDK's.
rm -rf "$out/include"
mkdir -p "$out/include"
cp -R "$relibc/include/." "$out/include/"
cp "$relibc/openlibm/include/"*.h "$relibc/openlibm/src/"*.h "$out/include/"
cp -R "$relibc/include-generated/." "$out/include/"
rm "$out/include/provenance.json"
cp "$here/moruna_function.h" "$out/include/"

# 3. openlibm, built from a copy so the vendored tree stays as it is.
rm -rf "$out/openlibm"
cp -R "$relibc/openlibm" "$out/openlibm"
make -s -C "$out/openlibm" libopenlibm.a OS=Linux ARCH=amd64 AR="$ar" \
  CC="$cc ${cflags[*]} ${includes[*]} -fno-builtin -Wno-everything" >/dev/null
cp "$out/openlibm/libopenlibm.a" "$out/lib/"

# 4. The C functions: each a static native program, its entry std's _start.
compile() {
  local object
  object="$out/obj/$(basename "$1" .c).o"
  "$cc" "${cflags[@]}" "${includes[@]}" -std=c11 -Wall -Wextra -Werror -I"$here" \
    -c "$here/$1" -o "$object"
  echo "$object"
}
link() {
  local name="$1"
  shift
  # std's _start names the C library's start and end weakly, which takes no member of an
  # archive: a program on the C library names them outright (tests/threads.rs in its source).
  "$lld" -flavor gnu -static -no-pie -z norelro --gc-sections -T "$script" \
    --undefined=moruna_libc_init --undefined=moruna_libc_exit \
    -o "$out/obj/$name" "$@" "$out/lib/libmoruna_function.a" "$out/lib/libopenlibm.a"
}
# A program as a node fetches and registers it: stripped. Its debug info is kept beside the
# build, in debug/, which the program names. A program without the C library's start is refused.
strip_program() {
  local name="$1"
  "$tools/llvm-nm" "$out/obj/$name" | grep ' T moruna_libc_init$' >/dev/null || {
    echo "build-core.sh: $name has no moruna_libc_init: the C library would not start" >&2
    exit 1
  }
  "$objcopy" --only-keep-debug "$out/obj/$name" "$out/debug/$name.debug"
  (cd "$out/debug" && "$objcopy" --strip-all --add-gnu-debuglink="$name.debug" \
    "$out/obj/$name" "$out/bin/$name")
}
link double "$(compile examples/double.c)"
link sum "$(compile tests/c/sum.c)" "$(compile tests/c/scenarios.c)" "$(compile tests/c/support.c)"
link runtime "$(compile tests/c/runtime.c)"
link params "$(compile tests/c/params.c)" "$(compile tests/c/support.c)"
cp "$threads" "$out/obj/threads"
for name in double sum runtime params threads; do
  strip_program "$name"
done

# 5. relibc's own C tests that need only what Moruna has (no files, processes, signals or
# sockets; not pthread/barrier, which takes an atomic clang refuses, nor pthread/exit and
# stdlib/div, which end their process themselves), as one static program, bin/libc-tests, the
# boot's (kernel/initramfs/boot.image): each test's `main` renamed and its other symbols made its
# own, called in turn by a runner that says each one's end and stops at the first that fails.
# Compiled with relibc's test flags (tests/Makefile), less clang's -Wstrict-prototypes, which its
# sources predate.
libc_tests=(constructor destructor tls ctype alloca endian math
  string/mem string/strchr string/strcat string/stpcpy
  stdlib/strtol stdlib/strtoul stdlib/atoi stdlib/atof stdlib/qsort stdlib/a64l
  stdlib/alloc stdlib/rand48
  stdio/printf stdio/sprintf stdio/printf_neg_pad stdio/printf_space_pad
  pthread/once pthread/mutex_recursive pthread/cleanup pthread/tls pthread/extjoin
  pthread/rwlock_trylock pthread/timeout pthread/timedwait)
runner="$out/obj/libc-tests.c"
objects=()
{
  echo '#include <stdio.h>'
  for i in "${!libc_tests[@]}"; do echo "int libc_test_$i(void);"; done
  echo 'static const struct { const char *name; int (*main)(void); } tests[] = {'
  for i in "${!libc_tests[@]}"; do echo "  {\"${libc_tests[$i]}\", libc_test_$i},"; done
  echo '};'
  echo 'int main(void) {'
  echo '  for (size_t i = 0; i < sizeof tests / sizeof tests[0]; i++) {'
  echo '    fflush(stdout);'
  echo '    int code = tests[i].main();'
  echo '    if (code != 0) {'
  echo '      printf("libc-tests: FAIL: %s returned %d\n", tests[i].name, code);'
  echo '      return 1;'
  echo '    }'
  echo '    printf("libc-tests: %s: ok\n", tests[i].name);'
  echo '  }'
  echo '  printf("libc-tests: ok: %zu tests\n", sizeof tests / sizeof tests[0]);'
  echo '  return 0;'
  echo '}'
} >"$runner"
for i in "${!libc_tests[@]}"; do
  object="$out/obj/libc-test-$i.o"
  "$cc" "${cflags[@]}" "${includes[@]}" -fno-builtin -Wall -Wextra -Werror \
    -Wno-deprecated-declarations -Wno-strict-prototypes -pedantic -I"$relibc/tests" \
    -c "$relibc/tests/${libc_tests[$i]}.c" -o "$object"
  # Renamed once compiled, so a `main` that ends without `return` still returns 0, as C says.
  "$objcopy" --redefine-sym "main=libc_test_$i" "$object"
  "$objcopy" --keep-global-symbol="libc_test_$i" "$object"
  objects+=("$object")
done
"$cc" "${cflags[@]}" "${includes[@]}" -std=c11 -Wall -Wextra -Werror -c "$runner" \
  -o "$out/obj/libc-tests-runner.o"
link libc-tests "$out/obj/libc-tests-runner.o" "${objects[@]}"
strip_program libc-tests
ls -l "$out/bin" "$out/debug"
