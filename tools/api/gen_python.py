#!/usr/bin/env python3
"""Write ``python/moruna/api/_generated.py`` from the node API's OpenAPI document.

System design 2E, item 2.5. The generated module holds one class per schema of
``kernel/api/openapi.json`` (a dataclass for each object, a ``StrEnum`` for each set of string
constants) and one function per operation, which calls it through a client and reads its answer.
The client itself is hand-written beside it, in ``python/moruna/api/__init__.py``.

Usage::

    tools/api/gen_python.py            # write the module
    tools/api/gen_python.py --check    # exit 1 when the committed module is not what is generated

``--openapi`` and ``--output`` name other files, for tests. The output is byte for byte stable.
The generator reads only the schema shapes the document uses; any other shape stops it with an
error naming the schema, so a new shape is taught here before it is generated wrongly.
"""

from __future__ import annotations

import argparse
import json
import keyword
import sys
import textwrap
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
OPENAPI = ROOT / "kernel" / "api" / "openapi.json"
OUTPUT = ROOT / "python" / "moruna" / "api" / "_generated.py"
WIDTH = 100
REF = "#/components/schemas/"


class Unsupported(Exception):
    """The document uses a schema shape this generator does not read."""


HEADER = '''\
# Generated by tools/api/gen_python.py from kernel/api/openapi.json. Do not edit: change the
# API's types in kernel/api/types, regenerate the document, then run tools/api/gen_python.py.
"""The node API's types and operations, generated from its OpenAPI document (system design 2E).

Each object schema is a frozen dataclass with ``from_json``, which checks an answer's fields and
their types, and ``to_json``; each set of string constants is a ``StrEnum``. Each operation is a
function that calls it through a client (``moruna.api.Client``) and reads its answer.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from typing import Any, Protocol


class Caller(Protocol):
    """What an operation is called through: ``moruna.api.Client``."""

    def call(self, operation: str, method: str, path: str, *, token: bool) -> Any:
        """Call ``method path`` (with the token when ``token``) and return the JSON answer."""
        ...


def _object(value: Any, where: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise ValueError(f"{where}: expected an object, found {type(value).__name__}")
    return value


def _at(data: dict[str, Any], key: str, where: str) -> tuple[Any, str]:
    if key not in data:
        raise ValueError(f"{where}: missing field {key!r}")
    return data[key], f"{where}.{key}"


def _items(value: Any, where: str) -> list[tuple[Any, str]]:
    if not isinstance(value, list):
        raise ValueError(f"{where}: expected a list, found {type(value).__name__}")
    return [(item, f"{where}[{i}]") for i, item in enumerate(value)]


def _str(value: Any, where: str) -> str:
    if not isinstance(value, str):
        raise ValueError(f"{where}: expected a string, found {type(value).__name__}")
    return value


def _int(value: Any, where: str, low: int | None, high: int | None) -> int:
    if not isinstance(value, int) or isinstance(value, bool):
        raise ValueError(f"{where}: expected an integer, found {type(value).__name__}")
    if (low is not None and value < low) or (high is not None and value > high):
        raise ValueError(f"{where}: {value} is out of range")
    return value


def _enum[E: StrEnum](kind: type[E], value: Any, where: str) -> E:
    text = _str(value, where)
    try:
        return kind(text)
    except ValueError:
        raise ValueError(f"{where}: {text!r} is not a {kind.__name__}") from None
'''


def docstring(text: str, indent: str) -> list[str]:
    """A docstring of ``text``, wrapped to the line width at this indent."""
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').strip()
    paragraphs = [" ".join(p.split()) for p in text.split("\n\n")]
    width = WIDTH - len(indent)
    lines: list[str] = []
    for i, paragraph in enumerate(paragraphs):
        if i:
            lines.append("")
        lines.extend(textwrap.wrap(paragraph, width=width - 3, break_on_hyphens=False))
    if len(lines) == 1 and len(lines[0]) + 6 <= width:
        return [f'{indent}"""{lines[0]}"""']
    lines[0] = '"""' + lines[0]
    return [f"{indent}{line}".rstrip() for line in lines] + [f'{indent}"""']


def is_enum(schema: dict[str, Any]) -> bool:
    """Whether a schema is a set of string constants."""
    one_of = schema.get("oneOf")
    return isinstance(one_of, list) and all(
        isinstance(c, dict) and c.get("type") == "string" and "const" in c for c in one_of
    )


def member(value: str) -> str:
    """The Python name of an enum constant."""
    name = "".join(ch if ch.isalnum() else "_" for ch in value).upper()
    return "_" + name if not name or name[0].isdigit() else name


class Generator:
    """Writes the module for one OpenAPI document."""

    def __init__(self, document: dict[str, Any]) -> None:
        self.schemas: dict[str, dict[str, Any]] = document["components"]["schemas"]
        self.paths: dict[str, dict[str, Any]] = document["paths"]

    def ref(self, schema: dict[str, Any], where: str) -> str:
        """The name of the schema a ``$ref`` names."""
        target = str(schema["$ref"])
        if not target.startswith(REF) or target[len(REF) :] not in self.schemas:
            raise Unsupported(f"{where}: a reference outside the document's schemas: {target}")
        return target[len(REF) :]

    def annotation(self, schema: dict[str, Any], where: str) -> str:
        """The Python type of a field's schema."""
        if "$ref" in schema:
            return self.ref(schema, where)
        kind = schema.get("type")
        if kind == "string":
            return "str"
        if kind == "integer":
            return "int"
        if kind == "array":
            return f"list[{self.annotation(schema['items'], where + '[]')}]"
        raise Unsupported(f"{where}: a field schema of type {kind!r}")

    def read(self, schema: dict[str, Any], value: str, where: str) -> str:
        """An expression that reads ``value``, a ``(value, location)`` pair, as ``schema``."""
        if "$ref" in schema:
            name = self.ref(schema, where)
            if is_enum(self.schemas[name]):
                return f"_enum({name}, *{value})"
            return f"{name}.from_json(*{value})"
        # The field's annotation was made first, so its type is one of these three.
        kind = schema.get("type")
        if kind == "string":
            return f"_str(*{value})"
        if kind == "array":
            item = self.read(schema["items"], "item", where + "[]")
            return f"[{item} for item in _items(*{value})]"
        return f"_int(*{value}, {schema.get('minimum')}, {schema.get('maximum')})"

    def write(self, schema: dict[str, Any], value: str, where: str) -> str:
        """An expression that writes ``value`` back to JSON."""
        if "$ref" in schema:
            if is_enum(self.schemas[self.ref(schema, where)]):
                return f"{value}.value"
            return f"{value}.to_json()"
        if schema.get("type") == "array":
            return f"[{self.write(schema['items'], 'item', where)} for item in {value}]"
        return value

    def enum(self, name: str, schema: dict[str, Any]) -> list[str]:
        lines = [f"class {name}(StrEnum):", *docstring(schema.get("description", name), "    ")]
        for constant in schema["oneOf"]:
            lines.append("")
            lines.append(f'    {member(constant["const"])} = "{constant["const"]}"')
            if "description" in constant:
                lines.extend(docstring(constant["description"], "    "))
        return lines

    def dataclass(self, name: str, schema: dict[str, Any]) -> list[str]:
        if schema.get("type") != "object" or not isinstance(schema.get("properties"), dict):
            raise Unsupported(f"{name}: neither an object nor a set of string constants")
        properties: dict[str, dict[str, Any]] = schema["properties"]
        required = [key for key in schema.get("required", []) if key in properties]
        if len(required) != len(properties):
            raise Unsupported(f"{name}: an optional field")
        lines = [
            "@dataclass(frozen=True, slots=True)",
            f"class {name}:",
            *docstring(schema.get("description", name), "    "),
        ]
        for key in required:
            if not key.isidentifier() or keyword.iskeyword(key):
                raise Unsupported(f"{name}.{key}: not a Python name")
            lines.append("")
            lines.append(f"    {key}: {self.annotation(properties[key], f'{name}.{key}')}")
            if "description" in properties[key]:
                lines.extend(docstring(properties[key]["description"], "    "))
        lines += [
            "",
            "    @classmethod",
            f'    def from_json(cls, value: Any, where: str = "{name}") -> {name}:',
            '        """Read an answer\'s JSON value; a ``ValueError`` says where it is wrong."""',
            "        data = _object(value, where)",
            "        return cls(",
        ]
        for key in required:
            read = self.read(properties[key], f'_at(data, "{key}", where)', f"{name}.{key}")
            line = f"            {key}={read},"
            if len(line) > WIDTH and read.startswith("["):
                # As ruff formats it: the comprehension on its own line.
                lines += [f"            {key}=[", f"                {read[1:-1]}", "            ],"]
            else:
                lines.append(line)
        lines += [
            "        )",
            "",
            "    def to_json(self) -> dict[str, Any]:",
            '        """The JSON value, as the node writes it."""',
            "        return {",
        ]
        for key in required:
            lines.append(f'            "{key}": {self.write(properties[key], f"self.{key}", key)},')
        lines.append("        }")
        return lines

    def operations(self) -> list[list[str]]:
        functions = []
        for path in sorted(self.paths):
            for method in sorted(self.paths[path]):
                op = self.paths[path][method]
                name = op["operationId"]
                answer = op["responses"]["200"]["content"]["application/json"]["schema"]
                result = self.ref(answer, f"{name}'s answer")
                security = op.get("security", [])
                scopes = [
                    scope for entry in security for scopes in entry.values() for scope in scopes
                ]
                needs = f"a token with scope ``{scopes[0]}``" if scopes else "no token"
                token = "True" if security else "False"
                text = f"{op['summary']}\n\n``{method.upper()} {path}``, {needs}."
                functions.append(
                    [
                        f"def {name}(client: Caller) -> {result}:",
                        *docstring(text, "    "),
                        f'    answer = client.call("{name}", "{method.upper()}", "{path}", '
                        f"token={token})",
                        f"    return {result}.from_json(answer)",
                    ]
                )
        return functions

    def module(self) -> str:
        blocks: list[list[str]] = []
        for name in sorted(self.schemas):
            schema = self.schemas[name]
            blocks.append(
                self.enum(name, schema) if is_enum(schema) else self.dataclass(name, schema)
            )
        blocks += self.operations()
        body = "\n\n\n".join("\n".join(block) for block in blocks)
        return f"{HEADER}\n\n{body}\n"


def generate(openapi: Path) -> str:
    """The module for the document at ``openapi``."""
    return Generator(json.loads(openapi.read_text(encoding="utf-8"))).module()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--openapi", type=Path, default=OPENAPI, help="the OpenAPI document")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="the module to write")
    parser.add_argument(
        "--check", action="store_true", help="exit 1 when the module is not what is generated"
    )
    args = parser.parse_args(argv)
    try:
        module = generate(args.openapi)
    except Unsupported as error:
        print(f"gen_python: {args.openapi}: unsupported schema: {error}", file=sys.stderr)
        return 1
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else None
        if current != module:
            print(
                f"gen_python: {args.output} is not what {args.openapi} generates; "
                "run tools/api/gen_python.py",
                file=sys.stderr,
            )
            return 1
        return 0
    args.output.write_text(module, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
